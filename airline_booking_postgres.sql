DROP VIEW  IF EXISTS v_flight_details;
DROP TABLE IF EXISTS payments CASCADE;
DROP TABLE IF EXISTS bookings CASCADE;
DROP TABLE IF EXISTS flights CASCADE;
DROP TABLE IF EXISTS passengers CASCADE;
DROP TABLE IF EXISTS airports CASCADE;
DROP TABLE IF EXISTS airlines CASCADE;

-- ---------------------------------------------------------------------
-- 1. SCHEMA
-- ---------------------------------------------------------------------
CREATE TABLE airlines (
    airline_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(80) NOT NULL,
    iata_code    CHAR(2)     NOT NULL UNIQUE,
    country      VARCHAR(50) NOT NULL
);

CREATE TABLE airports (
    airport_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iata_code    CHAR(3)     NOT NULL UNIQUE,
    name         VARCHAR(100) NOT NULL,
    city         VARCHAR(50) NOT NULL,
    country      VARCHAR(50) NOT NULL
);

CREATE TABLE flights (
    flight_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number  VARCHAR(10) NOT NULL,
    airline_id     INTEGER NOT NULL REFERENCES airlines(airline_id),
    origin_id      INTEGER NOT NULL REFERENCES airports(airport_id),
    destination_id INTEGER NOT NULL REFERENCES airports(airport_id),
    departure_time TIMESTAMP NOT NULL,
    arrival_time   TIMESTAMP NOT NULL,
    base_price     DECIMAL(10,2) NOT NULL CHECK (base_price > 0),
    total_seats    INTEGER NOT NULL CHECK (total_seats > 0),
    CHECK (origin_id <> destination_id),
    CHECK (arrival_time > departure_time)
);

CREATE TABLE passengers (
    passenger_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR(50)  NOT NULL,
    last_name     VARCHAR(50)  NOT NULL,
    email         VARCHAR(100) NOT NULL UNIQUE,
    phone         VARCHAR(20),
    nationality   VARCHAR(50),
    date_of_birth DATE NOT NULL
);

CREATE TABLE bookings (
    booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id  INTEGER NOT NULL REFERENCES passengers(passenger_id),
    flight_id     INTEGER NOT NULL REFERENCES flights(flight_id),
    booking_date  DATE NOT NULL,
    seat_number   VARCHAR(4) NOT NULL,
    travel_class  VARCHAR(10) NOT NULL CHECK (travel_class IN ('Economy','Business','First')),
    status        VARCHAR(10) NOT NULL CHECK (status IN ('Confirmed','Cancelled','Completed')),
    fare          DECIMAL(10,2) NOT NULL CHECK (fare >= 0),
    UNIQUE (flight_id, seat_number)            -- a seat can only be sold once per flight
);

CREATE TABLE payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    INTEGER NOT NULL REFERENCES bookings(booking_id),
    amount        DECIMAL(10,2) NOT NULL CHECK (amount >= 0),
    method        VARCHAR(15) NOT NULL CHECK (method IN ('Credit Card','Debit Card','UPI','Net Banking','PayPal')),
    status        VARCHAR(10) NOT NULL CHECK (status IN ('Paid','Pending','Failed','Refunded')),
    payment_date  DATE NOT NULL
);

-- ---------------------------------------------------------------------
-- 2. INDEXES (speed up the joins/filters used in the analysis below)
-- ---------------------------------------------------------------------
CREATE INDEX idx_flights_airline     ON flights(airline_id);
CREATE INDEX idx_flights_route       ON flights(origin_id, destination_id);
CREATE INDEX idx_bookings_passenger  ON bookings(passenger_id);
CREATE INDEX idx_bookings_flight     ON bookings(flight_id);
CREATE INDEX idx_bookings_date       ON bookings(booking_date);
CREATE INDEX idx_payments_booking    ON payments(booking_id);

