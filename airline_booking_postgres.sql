-- Payments are derived from booking status (one payment per booking):
--   Completed -> Paid | Confirmed -> Paid (except a few Pending) | Cancelled -> Refunded
INSERT INTO payments (payment_id, booking_id, amount, method, status, payment_date)
SELECT b.booking_id,
       b.booking_id,
       b.fare,
       CASE b.booking_id % 5
            WHEN 0 THEN 'Credit Card'
            WHEN 1 THEN 'UPI'
            WHEN 2 THEN 'Debit Card'
            WHEN 3 THEN 'Net Banking'
            ELSE 'PayPal' END,
       CASE WHEN b.status = 'Cancelled'            THEN 'Refunded'
            WHEN b.booking_id IN (31, 32)          THEN 'Pending'
            ELSE 'Paid' END,
       b.booking_date
FROM bookings b;

