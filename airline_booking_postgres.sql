-- ---------------------------------------------------------------------
-- 4. VIEW: one row per flight with airline + route (reused below)
-- ---------------------------------------------------------------------
CREATE VIEW v_flight_details AS
SELECT f.flight_id,
       f.flight_number,
       a.name          AS airline,
       o.city          AS origin_city,
       d.city          AS destination_city,
       f.departure_time,
       f.arrival_time,
       f.base_price,
       f.total_seats
FROM flights  f
JOIN airlines a ON a.airline_id = f.airline_id
JOIN airports o ON o.airport_id = f.origin_id
JOIN airports d ON d.airport_id = f.destination_id;

-- ---------------------------------------------------------------------
-- 5. ANALYSIS QUERIES
-- ---------------------------------------------------------------------

-- Q1. Flight details (JOIN via view)
SELECT flight_number, airline, origin_city, destination_city, departure_time, base_price
FROM v_flight_details
ORDER BY departure_time;

-- Q2. Full booking report: passenger, flight, route, class, status (multi-table JOIN)
SELECT b.booking_id,
       p.first_name || ' ' || p.last_name AS passenger,
       fd.flight_number,
       fd.origin_city || ' -> ' || fd.destination_city AS route,
       b.travel_class, b.status, b.fare
FROM bookings b
JOIN passengers p         ON p.passenger_id = b.passenger_id
JOIN v_flight_details fd  ON fd.flight_id   = b.flight_id
ORDER BY b.booking_id;

-- Q3. Total revenue (only money actually retained: Paid payments)
SELECT SUM(amount) AS total_revenue
FROM payments
WHERE status = 'Paid';

-- Q4. Revenue by airline (aggregation + JOINs)
SELECT a.name AS airline,
       COUNT(DISTINCT b.booking_id) AS paid_bookings,
       SUM(pay.amount)              AS revenue
FROM payments pay
JOIN bookings b ON b.booking_id = pay.booking_id
JOIN flights  f ON f.flight_id  = b.flight_id
JOIN airlines a ON a.airline_id = f.airline_id
WHERE pay.status = 'Paid'
GROUP BY a.airline_id, a.name
ORDER BY revenue DESC;

-- Q5. Most popular destinations (excluding cancelled bookings)
SELECT d.city AS destination, d.country,
       COUNT(*) AS bookings
FROM bookings b
JOIN flights  f ON f.flight_id   = b.flight_id
JOIN airports d ON d.airport_id  = f.destination_id
WHERE b.status <> 'Cancelled'
GROUP BY d.airport_id, d.city, d.country
ORDER BY bookings DESC, destination
LIMIT 5;

-- Q6. Monthly booking trend
SELECT TO_CHAR(booking_date, 'YYYY-MM') AS month,
       COUNT(*)  AS bookings,
       SUM(fare) AS booked_value
FROM bookings
GROUP BY month
ORDER BY month;

-- Q7. Month-over-month growth in bookings (CTE + window function LAG)
WITH monthly AS (
    SELECT TO_CHAR(booking_date, 'YYYY-MM') AS month, COUNT(*) AS bookings
    FROM bookings
    GROUP BY month
)
SELECT month,
       bookings,
       LAG(bookings) OVER (ORDER BY month) AS prev_month,
       ROUND(100.0 * (bookings - LAG(bookings) OVER (ORDER BY month))
                   / LAG(bookings) OVER (ORDER BY month), 1) AS growth_pct
FROM monthly;

-- Q8. Seat occupancy per flight (aggregation + arithmetic)
SELECT fd.flight_number,
       fd.origin_city || ' -> ' || fd.destination_city AS route,
       fd.total_seats,
       COUNT(b.booking_id) AS seats_sold,
       ROUND(100.0 * COUNT(b.booking_id) / fd.total_seats, 2) AS occupancy_pct
FROM v_flight_details fd
LEFT JOIN bookings b ON b.flight_id = fd.flight_id AND b.status <> 'Cancelled'
GROUP BY fd.flight_id, fd.flight_number, fd.origin_city, fd.destination_city, fd.total_seats
ORDER BY occupancy_pct DESC;

-- Q9. Passengers with no active trips: never booked, or only cancelled (LEFT JOIN ... IS NULL)
SELECT p.passenger_id, p.first_name, p.last_name, p.email
FROM passengers p
LEFT JOIN bookings b ON b.passenger_id = p.passenger_id AND b.status <> 'Cancelled'
WHERE b.booking_id IS NULL;

-- Q10. Airlines with no flights that have bookings (subquery with NOT IN)
SELECT name
FROM airlines
WHERE airline_id NOT IN (
    SELECT DISTINCT f.airline_id
    FROM flights f
    JOIN bookings b ON b.flight_id = f.flight_id
);

-- Q11. Passengers who spent more than the average passenger (subquery in HAVING)
SELECT p.first_name || ' ' || p.last_name AS passenger,
       SUM(pay.amount) AS total_spent
FROM passengers p
JOIN bookings b    ON b.passenger_id = p.passenger_id
JOIN payments pay  ON pay.booking_id = b.booking_id
WHERE pay.status = 'Paid'
GROUP BY p.passenger_id, p.first_name, p.last_name
HAVING SUM(pay.amount) > (
    SELECT AVG(per_passenger)
    FROM (
        SELECT SUM(pay2.amount) AS per_passenger
        FROM bookings b2
        JOIN payments pay2 ON pay2.booking_id = b2.booking_id
        WHERE pay2.status = 'Paid'
        GROUP BY b2.passenger_id
    ) AS totals
)
ORDER BY total_spent DESC;

-- Q12. Frequent flyers: passengers with 3+ non-cancelled bookings
SELECT p.first_name || ' ' || p.last_name AS passenger,
       COUNT(*) AS trips
FROM passengers p
JOIN bookings b ON b.passenger_id = p.passenger_id
WHERE b.status <> 'Cancelled'
GROUP BY p.passenger_id, p.first_name, p.last_name
HAVING COUNT(*) >= 3
ORDER BY trips DESC;

-- Q13. Cancellation rate by airline
SELECT a.name AS airline,
       COUNT(*) AS total_bookings,
       SUM(CASE WHEN b.status = 'Cancelled' THEN 1 ELSE 0 END) AS cancelled,
       ROUND(100.0 * SUM(CASE WHEN b.status = 'Cancelled' THEN 1 ELSE 0 END) / COUNT(*), 1) AS cancel_rate_pct
FROM bookings b
JOIN flights  f ON f.flight_id  = b.flight_id
JOIN airlines a ON a.airline_id = f.airline_id
GROUP BY a.airline_id, a.name
ORDER BY cancel_rate_pct DESC;

-- Q14. Revenue and share by travel class
SELECT b.travel_class,
       COUNT(*) AS bookings,
       SUM(pay.amount) AS revenue,
       ROUND(100.0 * SUM(pay.amount) / SUM(SUM(pay.amount)) OVER (), 1) AS revenue_share_pct
FROM bookings b
JOIN payments pay ON pay.booking_id = b.booking_id
WHERE pay.status = 'Paid'
GROUP BY b.travel_class
ORDER BY revenue DESC;

-- Q15. Payment method popularity and status breakdown
SELECT method,
       COUNT(*) AS payments,
       SUM(CASE WHEN status = 'Paid'     THEN 1 ELSE 0 END) AS paid,
       SUM(CASE WHEN status = 'Pending'  THEN 1 ELSE 0 END) AS pending,
       SUM(CASE WHEN status = 'Refunded' THEN 1 ELSE 0 END) AS refunded
FROM payments
GROUP BY method
ORDER BY payments DESC;

-- Q16. Top-earning route per airline (window function RANK in a CTE)
WITH route_rev AS (
    SELECT a.name AS airline,
           fd.origin_city || ' -> ' || fd.destination_city AS route,
           SUM(pay.amount) AS revenue
    FROM payments pay
    JOIN bookings b        ON b.booking_id  = pay.booking_id
    JOIN v_flight_details fd ON fd.flight_id = b.flight_id
    JOIN flights f         ON f.flight_id   = fd.flight_id
    JOIN airlines a        ON a.airline_id  = f.airline_id
    WHERE pay.status = 'Paid'
    GROUP BY a.name, fd.origin_city, fd.destination_city
),
ranked AS (
    SELECT *, RANK() OVER (PARTITION BY airline ORDER BY revenue DESC) AS rnk
    FROM route_rev
)
SELECT airline, route, revenue
FROM ranked
WHERE rnk = 1
ORDER BY revenue DESC;

-- Q17. Data-quality check: bookings whose payment amount doesn't match the fare
SELECT b.booking_id, b.fare, pay.amount
FROM bookings b
JOIN payments pay ON pay.booking_id = b.booking_id
WHERE pay.amount <> b.fare;

-- Q18. Pending payments needing follow-up (with passenger contact)
SELECT p.first_name || ' ' || p.last_name AS passenger, p.email, pay.amount, pay.payment_date
FROM payments pay
JOIN bookings b   ON b.booking_id   = pay.booking_id
JOIN passengers p ON p.passenger_id = b.passenger_id
WHERE pay.status = 'Pending';

